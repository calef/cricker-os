#[cfg(test)]
mod tests {
    use super::BASIC;
    extern crate std;
    use std::string::String;

    /// **The picture and the bits are the same font.**
    ///
    /// `kaypro-style-7x8.art` is what a person edits and reviews, because hexadecimal is not a
    /// medium anyone can see a letter in; the table above is what compiles. Two representations of
    /// one thing is a drift bug waiting to happen, so the `.art` is parsed here and compared. A
    /// glyph fixed in one and not the other fails at `cargo test -p bitfont` rather than on a
    /// screen.
    #[test]
    fn the_art_file_and_this_table_agree() {
        let art = include_str!("../kaypro-style-7x8.art");
        let mut drawn = [[0u8; 8]; 128];
        let mut current: Option<usize> = None;
        let mut row = 0usize;
        for line in art.lines() {
            let line = line.trim_end();
            if line.trim_start().starts_with(';') || line.trim().is_empty() {
                continue;
            }
            if let Some(rest) = line.trim_start().strip_prefix('@') {
                let code = rest.split_whitespace().next().unwrap_or("");
                current = usize::from_str_radix(code, 16).ok();
                assert!(current.is_some(), "unparsable code point in {line:?}");
                row = 0;
                continue;
            }
            let code = current.expect("a picture row before any @ code point");
            assert!(row < 8, "glyph {code:#04x} has more than eight rows");
            assert_eq!(
                line.chars().count(),
                7,
                "glyph {code:#04x} row {row} is not seven columns"
            );
            for (x, ch) in line.chars().enumerate() {
                assert!(ch == '#' || ch == '.', "glyph {code:#04x} has {ch:?} in it");
                if ch == '#' {
                    drawn[code][row] |= 1 << x;
                }
            }
            row += 1;
        }
        for byte in 0..128usize {
            assert_eq!(
                drawn[byte],
                BASIC[byte],
                "{:#04x} differs between kaypro-style-7x8.art and this table:\n{}",
                byte,
                side_by_side(&drawn[byte], &BASIC[byte]),
            );
        }
    }

    /// The two shapes as pictures, because a diff of sixteen hex bytes says nothing.
    fn side_by_side(art: &[u8; 8], table: &[u8; 8]) -> String {
        let mut out = String::from("  art     table\n");
        for y in 0..8 {
            for &rows in &[art, table] {
                for x in 0..7 {
                    out.push(if rows[y] >> x & 1 != 0 { '#' } else { '.' });
                }
                out.push_str("  ");
            }
            out.push('\n');
        }
        out
    }
}
