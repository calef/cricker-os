//! **The glyph bitmaps** (milestone 29). Generated data, kept in its own file so the code that
//! *uses* a font is not buried in 128 rows of hexadecimal.
//!
//! # Where these bits come from, and under what licence
//!
//! `font8x8` by Daniel Hepper <daniel@hepper.net>, **public domain**, which is itself derived from
//! Marcel Sondaar's `font8x8.h`, also public domain, which traces back to IBM's public-domain VGA
//! fonts. Upstream: <https://github.com/dhepper/font8x8> (`font8x8_basic.h`, the U+0000..U+007F
//! block). Transcribed here into Rust by a script; no bits were changed.
//!
//! Public domain is the reason this one was picked over the alternatives, and the reason is worth
//! stating: a bitmap font gets *compiled into the kernel image* and every binary that draws text,
//! so its licence is a licence on the artefact rather than on a build-time tool. Terminus (OFL-1.1)
//! and Spleen (BSD-2-Clause) are both fine fonts with compatible licences, and either would have
//! added an attribution obligation travelling with every image. This adds none. See
//! notes/glyphs.md.
//!
//! # The bit order, which is the one thing a font table gets wrong
//!
//! One byte per row, top row first. **Bit 0 is the LEFTMOST pixel** (little-endian within the row),
//! which is the opposite of the convention most bitmap fonts use and exactly the sort of thing that
//! produces a mirrored alphabet nobody notices until it is on a screen. `lib.rs` asserts it against
//! a glyph whose shape is asymmetric.

